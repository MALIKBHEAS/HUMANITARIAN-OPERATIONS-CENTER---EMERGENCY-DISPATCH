"""
EOA Global - AI Engine Rigid Schemas (The Hallucination Shield)
Enforces strict Pydantic v2 data models for zero-hallucination structured outputs.
Compatible with Python 3.8+ utilizing explicit typing constructs (List, Dict, Optional).
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class IncidentCategory(str, Enum):
    """
    Standard emergency categories: Medical, Fire, Security, Rescue.
    """
    MEDICAL = "Medical"
    FIRE = "Fire"
    SECURITY = "Security"
    RESCUE = "Rescue"


class AgencyType(str, Enum):
    """
    Public safety response agencies: Police, Hospital, CivilDefense.
    """
    POLICE = "Police"
    HOSPITAL = "Hospital"
    CIVIL_DEFENSE = "CivilDefense"


class IncidentClassification(BaseModel):
    """
    Categorization and critical severity ranking of the incoming SOS signal.
    """
    category: IncidentCategory = Field(
        ...,
        description="Incident category: Medical, Fire, Security, Rescue",
    )
    severity_level: int = Field(
        ...,
        ge=1,
        le=5,
        description="Emergency severity ranking from 1 (minor/routine) to 5 (catastrophic disaster)",
    )
    detected_language: Optional[str] = Field(
        default="English",
        description="Original language of the SOS signal (e.g., Arabic, English, Spanish, French)",
    )
    summary: Optional[str] = Field(
        None,
        description="Standardized tactical summary of the incident",
    )

    model_config = ConfigDict(use_enum_values=True)


class DispatchDecision(BaseModel):
    """
    Specific tactical dispatch decision per emergency response agency.
    """
    agency_type: AgencyType = Field(
        ...,
        description="Target responding agency: Police, Hospital, CivilDefense",
    )
    required_units: int = Field(
        ...,
        ge=1,
        le=50,
        description="Exact count of specialized mobile units/crews (e.g., ambulances, engines, patrol units) to mobilize",
    )
    reasoning: str = Field(
        ...,
        min_length=5,
        description="Factual, hallucination-free tactical justification derived strictly from verified facts in the SOS text",
    )

    model_config = ConfigDict(use_enum_values=True)


class AIResponse(BaseModel):
    """
    Root structured output schema generated by the AI Orchestration layer.
    """
    parsed_location: str = Field(
        ...,
        description="Extracted geographical landmark, address, street, or coordinates",
    )
    classification: IncidentClassification = Field(
        ...,
        description="Incident categorization and severity assessment",
    )
    dispatches: List[DispatchDecision] = Field(
        ...,
        min_length=1,
        description="List of multi-agency dispatch orders",
    )
    casualties_indicated: int = Field(
        default=0,
        ge=0,
        description="Number of estimated or confirmed casualties",
    )

    model_config = ConfigDict(use_enum_values=True)
